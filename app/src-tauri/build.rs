//! Release manifest, and the app's modules: every app/modules/<id>/ with a
//! module.rs becomes `crate::<id>` (its entry file), its setup/shutdown run
//! with the app and the commands listed in module.toml are registered. The
//! shell itself names no module.
use std::{fmt::Write, path::Path};

fn main() {
    let mut attributes = tauri_build::Attributes::new();
    // release: always run as administrator (nous-admin.manifest); debug keeps
    // the default so `tauri dev` starts from a normal terminal
    if std::env::var("PROFILE").as_deref() == Ok("release") {
        println!("cargo:rerun-if-changed=nous-admin.manifest");
        attributes = attributes.windows_attributes(
            tauri_build::WindowsAttributes::new().app_manifest(include_str!("nous-admin.manifest")),
        );
    }
    modules();
    tauri_build::try_build(attributes).expect("tauri build");
}

#[derive(serde::Deserialize)]
struct Manifest {
    id: String,
    #[serde(default)]
    rust: Rust,
}
#[derive(serde::Deserialize, Default)]
struct Rust {
    #[serde(default)]
    commands: Vec<String>,
}

fn modules() {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../modules");
    println!("cargo:rerun-if-changed={}", root.display());
    let mut found = Vec::new();
    for entry in std::fs::read_dir(&root).expect("app/modules") {
        let dir = entry.unwrap().path();
        let toml = dir.join("module.toml");
        println!("cargo:rerun-if-changed={}", toml.display());
        let Ok(text) = std::fs::read_to_string(&toml) else { continue };
        let manifest: Manifest =
            toml::from_str(&text).unwrap_or_else(|e| panic!("{}: {e}", toml.display()));
        let entry = dir.join("module.rs");
        if entry.is_file() {
            found.push((manifest.id.replace('-', "_"), entry, manifest.rust.commands));
        } else if !manifest.rust.commands.is_empty() {
            panic!("{}: [rust] commands without module.rs", toml.display());
        }
    }
    found.sort_by(|a, b| a.0.cmp(&b.0));

    let mut out = String::from("// Generated by build.rs from app/modules/*/module.toml.\n");
    for (name, entry, _) in &found {
        let path = entry.canonicalize().unwrap().display().to_string();
        writeln!(out, "#[path = {path:?}]\npub mod {name};").unwrap();
    }
    out.push_str("mod modules {\n    /// Starts every module's Rust side.\n    pub fn setup(app: &tauri::AppHandle) -> tauri::Result<()> {\n");
    for (name, ..) in &found {
        writeln!(out, "        crate::{name}::setup(app)?;").unwrap();
    }
    out.push_str("        Ok(())\n    }\n    pub fn shutdown(app: &tauri::AppHandle) {\n");
    for (name, ..) in &found {
        writeln!(out, "        crate::{name}::shutdown(app);").unwrap();
    }
    out.push_str("    }\n}\n/// tauri::generate_handler! with the shell's commands plus every module's.\nmacro_rules! handler_with_modules {\n    ($($shell:path),* $(,)?) => {\n        tauri::generate_handler![$($shell,)*");
    for (name, _, commands) in &found {
        for command in commands {
            write!(out, " {name}::{command},").unwrap();
        }
    }
    out.push_str("]\n    };\n}\n");
    std::fs::write(Path::new(&std::env::var("OUT_DIR").unwrap()).join("modules.rs"), out).unwrap();
}
