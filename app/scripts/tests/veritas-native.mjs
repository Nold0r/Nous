// Requires an isolated, built debug application and the loopback simulator.
import assert from 'node:assert/strict'
import { mkdir, readFile } from 'node:fs/promises'
import { resolve } from 'node:path'
import { chromium } from 'playwright'

const browser = await chromium.connectOverCDP(process.env.NOUS_CDP ?? 'http://127.0.0.1:9223')
const pages = browser.contexts()[0].pages()
const main = pages.find((p) => !/veritas-overlay|veritas-replay-target|devtools:/.test(p.url()))
const overlay = pages.find((p) => p.url().includes('#/veritas-overlay'))
assert.ok(main && overlay, 'main and actual overlay WebViews must exist')
const errors = []
for (const page of [main, overlay]) {
  page.setDefaultTimeout(15000)
  page.on('pageerror', (e) => errors.push(String(e)))
  page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()) })
}
const invoke = (cmd, args = {}) => main.evaluate(([cmd, args]) => window.__TAURI_INTERNALS__.invoke(cmd, args), [cmd, args])
assert.equal(await invoke('plugin:app|identifier'), 'com.nous.devtest', 'refuse production WebView')
const state = () => invoke('get_veritas_overlay')
assert.equal((await state()).replay, true, 'refuse a real game integration')
const wait = async (predicate) => {
  for (let i = 0; i < 150; i++) {
    const current = await state()
    if (predicate(current)) return current
    await new Promise((r) => setTimeout(r, 100))
  }
  assert.fail(`state timeout: ${JSON.stringify(await state())}`)
}
const post = async (path, body = {}) => {
  const response = await fetch(`http://127.0.0.1:1305${path}`, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify(body) })
  assert.equal(response.status, 200)
  return response.json()
}
const patch = async (changes) => invoke('set_veritas_overlay_settings', { settings: { ...(await state()).settings, ...changes } })
await post('/reconnect')
await wait((s) => s.snapshot.connected)
await post('/end')
await invoke('veritas_overlay_action', { action: 'show' })
await patch({ enabled: true, clickThrough: true, scale: 1, width: 650, height: 700, theme: 'nous', autoExport: false, exportDirectory: null,
  views: { legend: true, characters: true, metrics: true, breakdown: true, enemies: true, graph: true, logs: false } })
for (const command of ['enable_veritas', 'disable_veritas', 'launch_game']) {
  await assert.rejects(() => invoke(command, command === 'enable_veritas' ? { acceptRisk: true } : {}))
}
assert.equal((await invoke('get_veritas_status')).enabled, false)
await post('/begin')
await wait((s) => s.snapshot.active && s.presentation.visible)
for (let i = 0; i < 8; i++) await post('/turn')
const active = await wait((s) => s.snapshot.battle?.turnHistory.length === 8)
const fixture = await (await fetch('http://127.0.0.1:1305/state')).json()
assert.equal(active.snapshot.battle.totalDamage, fixture.total_damage)
const flags = await invoke('inspect_veritas_replay_window')
assert.equal(flags.visible, true)
assert.equal(flags.focused, false)
for (const flag of ['clickThrough', 'noActivate', 'topmost', 'toolWindow']) assert.equal(flags[flag], true, flag)
assert.ok(flags.width > 0 && flags.height > 0)
assert.equal(await overlay.evaluate(() => getComputedStyle(document.body).backgroundColor), 'rgba(0, 0, 0, 0)')
const evidence = resolve('../docs/Архитектура/Изображения')
await mkdir(evidence, { recursive: true })
await overlay.screenshot({ path: `${evidence}/Veritas — оверлей Nous — debug.png` })
await invoke('veritas_overlay_action', { action: 'hide' })
await wait((s) => !s.presentation.visible)
await invoke('veritas_overlay_action', { action: 'show' })
await wait((s) => s.presentation.visible)
await invoke('set_veritas_replay_state', { targetVisible: false, exclusiveFullscreen: false })
await wait((s) => !s.presentation.visible)
assert.equal((await invoke('inspect_veritas_replay_window')).visible, false)
await invoke('set_veritas_replay_state', { targetVisible: true, exclusiveFullscreen: true })
const fullscreen = await wait((s) => s.presentation.exclusiveFullscreen && !s.presentation.visible)
assert.match(fullscreen.presentation.message, /безрамочн/)
await invoke('set_veritas_replay_state', { targetVisible: true, exclusiveFullscreen: false })
await wait((s) => s.presentation.visible)
await post('/end')
const ended = await wait((s) => !s.snapshot.active && !s.presentation.visible)
assert.equal((await invoke('inspect_veritas_replay_window')).visible, false)
assert.equal(ended.snapshot.battle.totalDamage, fixture.total_damage)
assert.ok(ended.snapshot.history.some((b) => b.id === ended.snapshot.battle.id))
const exported = await invoke('export_veritas_battle', { id: ended.snapshot.battle.id, format: 'both' })
assert.equal(exported.files.length, 2)
const json = JSON.parse(await readFile(exported.files.find((f) => f.endsWith('.json')), 'utf8'))
assert.equal(json.total_damage ?? json.totalDamage, fixture.total_damage)
assert.equal((await readFile(exported.files.find((f) => f.endsWith('.csv')), 'utf8')).split(/\r?\n/)[0].split(',').length, 24)
await patch({ exportDirectory: `${resolve('../target/veritas-native-test')}/../outside-replay` })
await assert.rejects(() => invoke('export_veritas_battle', { id: ended.snapshot.battle.id, format: 'json' }))
await patch({ exportDirectory: null })
const plugin = await invoke('read_veritas_plugin_config')
await assert.rejects(() => invoke('write_veritas_plugin_config', { options: { ...plugin.options, theme: Array(12).fill('Bogus') } }))
await invoke('write_veritas_plugin_config', { options: { ...plugin.options, locale: 'ru', suppressNative: true } })
const savedPlugin = await invoke('read_veritas_plugin_config')
assert.equal(savedPlugin.options.suppressNative, true)
assert.equal(savedPlugin.requiresRestart, true)
await post('/begin'); await post('/turn')
await wait((s) => s.presentation.visible)
await post('/disconnect')
await wait((s) => !s.snapshot.connected && !s.snapshot.active && !s.presentation.visible && s.snapshot.battle.interrupted)
await post('/reconnect')
await wait((s) => s.snapshot.connected)
await post('/turn')
await wait((s) => s.snapshot.active && s.snapshot.battle.partial)
await post('/end')
await wait((s) => !s.snapshot.active)
await main.evaluate(() => { location.hash = '/settings' })
await main.getByRole('heading', { name: 'Оверлей Nous', exact: true }).waitFor()
await main.getByRole('tab', { name: 'Оформление', exact: true }).click()
await main.getByRole('combobox', { name: 'Тема Nous', exact: true }).selectOption('light')
await wait((s) => s.settings.theme === 'light')
await main.reload()
await main.getByRole('heading', { name: 'Оверлей Nous', exact: true }).waitFor()
assert.equal((await state()).settings.theme, 'light')
await main.locator('.vt-controls').screenshot({ path: `${evidence}/Veritas — настройки Nous — debug.png` })
assert.deepEqual(errors, [])
console.log(JSON.stringify({ passed: true, nativeFlags: flags, damage: fixture.total_damage, history: (await state()).snapshot.history.length, exported: exported.files, checks: ['lifecycle', 'disconnect/reconnect', 'target gone', 'fullscreen hint', 'focus/clickthrough/styles', 'transparent CSS', 'history', 'JSON/CSV', 'path isolation', 'plugin validation', 'settings persistence', 'no JS errors'] }, null, 2))
await browser.close()
